"""Canonical Postgres schema for the shared clinic database.

This is the single definition used by the calendar app, the receptionist and
the migration tooling. It is intentionally idempotent so it can be executed as
a deploy/migration step. Always run it through the direct (unpooled) Neon
connection; pooled connections are for application traffic only.

The ``appointments`` columns ``notification_status``, ``arrived`` and
``created_by`` are part of the shared contract even though the calendar UI
does not use them directly: the receptionist backend relies on them. Keeping
them here prevents a freshly provisioned database from breaking that backend.
"""

SCHEMA = """
CREATE TABLE IF NOT EXISTS users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          TEXT NOT NULL,
    email         TEXT,
    phone         TEXT,
    role          TEXT NOT NULL DEFAULT 'receptionist',
    password_hash TEXT,
    active        BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS patients (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          TEXT NOT NULL,
    phone         TEXT NOT NULL UNIQUE,
    gender        TEXT,
    date_of_birth DATE,
    address       TEXT,
    created_at    TIMESTAMPTZ DEFAULT now()
);

CREATE TABLE IF NOT EXISTS doctor_profiles (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id          BIGINT REFERENCES users(id),
    specialization   TEXT NOT NULL,
    qualification    TEXT,
    experience_years INTEGER,
    consultation_fee NUMERIC(10, 2),
    room_number      TEXT,
    available        BOOLEAN NOT NULL DEFAULT TRUE,
    color            TEXT
);

CREATE TABLE IF NOT EXISTS doctor_schedules (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    doctor_id    BIGINT NOT NULL REFERENCES doctor_profiles(id) ON DELETE CASCADE,
    weekday      INTEGER NOT NULL,
    start_time   TIME NOT NULL,
    end_time     TIME NOT NULL,
    slot_minutes INTEGER NOT NULL DEFAULT 30
);

CREATE TABLE IF NOT EXISTS clinic_holidays (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scope        TEXT NOT NULL DEFAULT 'CLINIC',
    doctor_id    BIGINT REFERENCES doctor_profiles(id) ON DELETE CASCADE,
    holiday_date DATE NOT NULL,
    end_date     DATE,
    name         TEXT NOT NULL,
    type         TEXT NOT NULL DEFAULT 'PUBLIC_HOLIDAY'
);

CREATE TABLE IF NOT EXISTS appointments (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id          BIGINT NOT NULL REFERENCES patients(id),
    doctor_id           BIGINT NOT NULL REFERENCES doctor_profiles(id),
    appointment_date    DATE NOT NULL,
    appointment_time    TIME NOT NULL,
    reason              TEXT,
    description         TEXT,
    referred_by         TEXT,
    token_number        INTEGER,
    status              TEXT NOT NULL DEFAULT 'BOOKED',
    emergency           BOOLEAN NOT NULL DEFAULT FALSE,
    source              TEXT DEFAULT 'calendar',
    patient_address     TEXT,
    created_at          TIMESTAMPTZ DEFAULT now(),
    notification_status TEXT NOT NULL DEFAULT 'pending',
    arrived             BOOLEAN NOT NULL DEFAULT FALSE,
    created_by          TEXT
);

-- Databases created before the shared contract existed need the same columns.
ALTER TABLE appointments
    ADD COLUMN IF NOT EXISTS notification_status TEXT NOT NULL DEFAULT 'pending';
ALTER TABLE appointments
    ADD COLUMN IF NOT EXISTS arrived BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE appointments
    ADD COLUMN IF NOT EXISTS created_by TEXT;

CREATE TABLE IF NOT EXISTS audit_log (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor      TEXT NOT NULL,
    action     TEXT NOT NULL,
    entity     TEXT NOT NULL,
    entity_id  TEXT NOT NULL,
    detail     TEXT,
    created_at TIMESTAMPTZ DEFAULT now()
);

-- Receptionist-owned tables live in the same database so doctor name lookups
-- and patient memory work without a second datastore.
CREATE TABLE IF NOT EXISTS doctor_legacy_map (
    doctor_id   BIGINT PRIMARY KEY REFERENCES doctor_profiles(id) ON DELETE CASCADE,
    legacy_name TEXT NOT NULL UNIQUE,
    doctor_key  TEXT NOT NULL UNIQUE,
    color       TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS patient_profiles (
    user_id              TEXT PRIMARY KEY,
    patient_name         TEXT,
    patient_phone        TEXT UNIQUE,
    preferred_doctor     TEXT,
    medical_conditions   TEXT,
    allergies            TEXT,
    reported_symptoms    TEXT,
    preferences          TEXT,
    last_appointment_id  BIGINT REFERENCES appointments(id),
    conversation_summary TEXT,
    alias_of             TEXT,
    updated_at           TIMESTAMPTZ DEFAULT now()
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_doctor_schedule
    ON doctor_schedules (doctor_id, weekday, start_time, end_time, slot_minutes);

CREATE UNIQUE INDEX IF NOT EXISTS uq_active_slot
    ON appointments (doctor_id, appointment_date, appointment_time)
    WHERE status IN ('BOOKED', 'CONFIRMED', 'CHECKED_IN');

CREATE INDEX IF NOT EXISTS ix_appointments_date
    ON appointments (appointment_date);

-- Seed/import code checks this key manually; enforce it in the database too.
CREATE UNIQUE INDEX IF NOT EXISTS uq_clinic_holiday
    ON clinic_holidays (scope, holiday_date, name, COALESCE(doctor_id, 0));
"""

__all__ = ["SCHEMA"]
